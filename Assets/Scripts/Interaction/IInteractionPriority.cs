/// <summary>
/// 交互优先级：数值大的优先，同优先级再比距离。
///
/// 存在的理由：交互中枢原本只按「谁离得近」选目标，但容器类交互物（工具箱、收容台）
/// 的 Collider 会把内容物整个包住——玩家准心看向箱内道具时，射线必然先穿过箱体，
/// 于是容器的提示会盖掉真正想拿的那件道具的提示。
///
/// 让容器在"内容物可取"时声明较低优先级，内容物保持默认 0 即可自然胜出；
/// 容器里的东西取空后容器回到 0，仍能正常开合箱盖。
///
/// 不实现本接口的交互物一律视为 0，因此加这个接口不影响既有行为。
/// </summary>
public interface IInteractionPriority
{
    /// <summary>越大越优先。默认语义：0 = 普通，负数 = 让位给其他候选。</summary>
    int InteractionPriority { get; }
}
